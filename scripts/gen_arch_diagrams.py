def _mmd_id(package: str) -> str:
    return package.replace(".", "_").replace("-", "_")


def render_module_deps(modules: list[str], edges: Counter[tuple[str, str]]) -> str:
    known_pkgs = {package_of(m) for m in modules}
    qf = sorted(p for p in known_pkgs if p == "quant_fund" or p.startswith("quant_fund."))
    fx = sorted(p for p in known_pkgs if p == "fx1" or p.startswith("fx1."))
    ghost = sorted(
        {dst for (_, dst) in edges if dst not in known_pkgs}
        | {src for (src, _) in edges if src not in known_pkgs}
    )
    lines = [GENERATED_HEADER, "flowchart LR"]
    for group, title in (("quant_fund", "quant_fund (harness)"), ("fx1", "fx1 (model project)")):
        members = qf if group == "quant_fund" else fx
        lines.append(f'  subgraph {group}["{title}"]')
        for pkg in members:
            lines.append(f'    {_mmd_id(pkg)}["{pkg}"]')
        lines.append("  end")
    for pkg in ghost:
        lines.append(f'  {_mmd_id(pkg)}["{pkg}"]:::ghost')
    for (src, dst), count in sorted(edges.items()):
        if src == dst:
            continue
        lines.append(f"  {_mmd_id(src)} -->|{count}| {_mmd_id(dst)}")
    lines += [
        "  classDef ghost stroke-dasharray: 5 5,color:#888",
        "  %% ghost nodes are lazily referenced packages absent from this tree",
    ]
    return "\n".join(lines) + "\n"


