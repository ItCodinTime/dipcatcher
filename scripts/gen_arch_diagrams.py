def iter_source_modules(src: Path) -> list[tuple[str, Path, bool]]:
    """Return sorted ``(dotted_module, repo-relative path, is_package)``."""
    out: list[tuple[str, Path, bool]] = []
    for path in sorted(src.rglob("*.py")):
        rel = path.relative_to(src).with_suffix("")
        parts = list(rel.parts)
        is_package = parts[-1] == "__init__"
        if is_package:
            parts = parts[:-1]
        if parts:
            out.append((".".join(parts), path, is_package))
    return sorted(out)


def _resolve_from(module: str, level: int, name: str | None, is_package: bool) -> str:
    """Resolve ``from <name> import ...`` at ``level`` inside ``module``.

    ``level == 0`` is absolute. For relative imports, level 1 is the current
    package: the module's parent for a regular module, the package itself for
    an ``__init__``.
    """
    if level == 0:
        return name or ""
    parts = module.split(".")
    drop = level - (1 if is_package else 0)
    base = parts[: len(parts) - drop]
    return ".".join(base + ([name] if name else []))


def parse_first_party_imports(
    path: Path, module: str, is_package: bool, known_modules: set[str]
) -> set[str]:
    """First-party import targets referenced by ``path`` (stdlib ast only).

    Includes function-level imports: optional/lazy dependencies (e.g. the
    W1 ``quant_fund.pit`` vault) are still real edges in the source.

    One edge per import alias: ``from a.b import c`` resolves to ``a.b.c``
    when that submodule exists, else to ``a.b``.
    """
    tree = ast.parse(path.read_text(encoding="utf-8"))
    targets: set[str] = set()
    for node in ast.walk(tree):
        candidates: list[str] = []
        if isinstance(node, ast.Import):
            candidates = [alias.name for alias in node.names]
        elif isinstance(node, ast.ImportFrom):
            base = _resolve_from(module, node.level, node.module, is_package)
            if base:
                candidates = [
                    f"{base}.{alias.name}" if f"{base}.{alias.name}" in known_modules else base
                    for alias in node.names
                ]
        for cand in candidates:
            if cand.split(".")[0] in FIRST_PARTY_ROOTS:
                targets.add(cand)
    return targets


def package_of(module: str) -> str:
    """Aggregate a dotted module to its second-level package node."""
    parts = module.split(".")
    if len(parts) > 1 and parts[0] in FIRST_PARTY_ROOTS:
        return ".".join(parts[:2])
    return parts[0]


def collect_graph(
    root: Path,
) -> tuple[list[str], Counter[tuple[str, str]], set[tuple[str, str]]]:
    """Scan ``src``; return (sorted modules, package edge counts, module edges).

    Package edges count distinct first-party modules imported per package
    pair. Module edges are the exact ``(importer, imported)`` pairs — the
    manifest stores them so ``--check`` detects any first-party import
    change, including moves within a package.
    """
    src = root / "src"
    modules = iter_source_modules(src)
    known_modules = {name for name, _, _ in modules}
    edges: Counter[tuple[str, str]] = Counter()
    module_edges: set[tuple[str, str]] = set()
    for name, path, is_package in modules:
        src_pkg = package_of(name)
        for target in parse_first_party_imports(path, name, is_package, known_modules):
            edges[(src_pkg, package_of(target))] += 1
            module_edges.add((name, target))
    return [name for name, _, _ in modules], edges, module_edges


