def _top_level_symbols(path: Path) -> set[str]:
    """Top-level defs/classes/assignments plus ``Class.method`` members."""
    tree = ast.parse(path.read_text(encoding="utf-8"))
    names: set[str] = set()
    for node in tree.body:
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)):
            names.add(node.name)
        elif isinstance(node, ast.ClassDef):
            names.add(node.name)
            for sub in node.body:
                if isinstance(sub, (ast.FunctionDef, ast.AsyncFunctionDef)):
                    names.add(f"{node.name}.{sub.name}")
        elif isinstance(node, ast.Assign):
            for tgt in node.targets:
                if isinstance(tgt, ast.Name):
                    names.add(tgt.id)
        elif isinstance(node, ast.AnnAssign) and isinstance(node.target, ast.Name):
            names.add(node.target.id)
    return names


def verify_anchors(root: Path) -> list[str]:
    """Return a list of errors for missing modules/symbols (empty when clean)."""
    errors: list[str] = []
    cache: dict[str, set[str]] = {}
    for anchor, (rel, symbol) in sorted(ANCHORS.items()):
        path = root / rel
        if not path.is_file():
            errors.append(f"{anchor}: module file missing: {rel}")
            continue
        if symbol == "*":
            continue
        if rel not in cache:
            cache[rel] = _top_level_symbols(path)
        if symbol not in cache[rel]:
            errors.append(f"{anchor}: {symbol} not defined at top level of {rel}")
    return errors


