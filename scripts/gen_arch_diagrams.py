def generated_artifacts(root: Path) -> dict[str, str]:
    """Return ``{repo-relative path: content}`` for every generated file."""
    modules, edges, module_edges = collect_graph(root)
    return {
        str(ARCH_DIR / "module_deps.mmd"): render_module_deps(modules, edges),
        str(ARCH_DIR / "data_flow.mmd"): render_data_flow(),
        str(ARCH_DIR / "paper_loop_sequence.mmd"): render_paper_loop(),
        str(ARCH_DIR / "manifest.json"): json.dumps(
            {
                "schema_version": SCHEMA_VERSION,
                "generator": GENERATOR,
                "source_root": "src",
                "module_count": len(modules),
                "modules": sorted(modules),
                "package_edges": [
                    {"src": s, "dst": d, "imports": c} for (s, d), c in sorted(edges.items())
                ],
                "module_edges": [{"src": s, "dst": d} for (s, d) in sorted(module_edges)],
            },
            indent=2,
            sort_keys=True,
        )
        + "\n",
    }


def generated_blocks(artifacts: dict[str, str]) -> dict[str, str]:
    """Atlas-doc embed blocks keyed by marker name."""
    return {
        "module_deps": "```mermaid\n" + artifacts[str(ARCH_DIR / "module_deps.mmd")] + "```",
        "data_flow": "```mermaid\n" + artifacts[str(ARCH_DIR / "data_flow.mmd")] + "```",
        "paper_loop": "```mermaid\n" + artifacts[str(ARCH_DIR / "paper_loop_sequence.mmd")] + "```",
        "coverage": render_coverage(
            json.loads(artifacts[str(ARCH_DIR / "manifest.json")])["modules"],
            Counter(
                {
                    (e["src"], e["dst"]): e["imports"]
                    for e in json.loads(artifacts[str(ARCH_DIR / "manifest.json")])["package_edges"]
                }
            ),
        ),
    }


def splice_blocks(text: str, blocks: dict[str, str]) -> str:
    """Replace ``BEGIN/END GENERATED: name`` marker regions with fresh content."""
    out = text
    for name, body in blocks.items():
        begin = f"<!-- BEGIN GENERATED: {name} -->"
        end = f"<!-- END GENERATED: {name} -->"
        i = out.find(begin)
        j = out.find(end)
        if i < 0 or j < 0 or j < i:
            raise ValueError(f"atlas doc is missing marker pair for {name!r}")
        out = out[: i + len(begin)] + "\n" + body + "\n" + out[j:]
    return out


def write_all(root: Path) -> list[str]:
    errors = verify_anchors(root)
    if errors:
        raise SystemExit("anchor verification failed:\n" + "\n".join(errors))
    artifacts = generated_artifacts(root)
    written: list[str] = []
    for rel, content in artifacts.items():
        path = root / rel
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(content, encoding="utf-8")
        written.append(rel)
    atlas = root / ATLAS_DOC
    if atlas.is_file():
        text = splice_blocks(atlas.read_text(encoding="utf-8"), generated_blocks(artifacts))
        atlas.write_text(text, encoding="utf-8")
        written.append(str(ATLAS_DOC))
    return written


def stale_artifacts(root: Path) -> list[str]:
    """Return sorted repo-relative paths whose committed bytes differ from fresh."""
    errors = verify_anchors(root)
    if errors:
        raise SystemExit("anchor verification failed:\n" + "\n".join(errors))
    artifacts = generated_artifacts(root)
    stale: list[str] = []
    for rel, content in artifacts.items():
        path = root / rel
        if not path.is_file() or path.read_text(encoding="utf-8") != content:
            stale.append(rel)
    atlas = root / ATLAS_DOC
    if atlas.is_file():
        try:
            expected = splice_blocks(atlas.read_text(encoding="utf-8"), generated_blocks(artifacts))
        except ValueError:
            stale.append(str(ATLAS_DOC))
        else:
            if atlas.read_text(encoding="utf-8") != expected:
                stale.append(str(ATLAS_DOC))
    else:
        stale.append(str(ATLAS_DOC))
    return sorted(stale)


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    parser.add_argument("--check", action="store_true", help="verify committed artifacts are fresh")
    parser.add_argument("--stats", action="store_true", help="print scan stats as JSON")
    parser.add_argument(
        "--root", type=Path, default=None, help="repo root (default: script parent)"
    )
    args = parser.parse_args(argv)
    root = (args.root or repo_root()).resolve()

    if args.stats:
        modules, edges, module_edges = collect_graph(root)
        print(
            json.dumps(
                {
                    "modules": len(modules),
                    "packages": len({package_of(m) for m in modules}),
                    "cross_package_edges": sum(1 for (s, d) in edges if s != d),
                    "module_edges": len(module_edges),
                    "distinct_imports": sum(edges.values()),
                },
                sort_keys=True,
            )
        )
        return 0

    if args.check:
        stale = stale_artifacts(root)
        if stale:
            print("stale architecture artifacts — run `python scripts/gen_arch_diagrams.py`:")
            for rel in stale:
                print(f"  {rel}")
            return 1
        print("architecture diagrams are fresh")
        return 0

    written = write_all(root)
    for rel in written:
        print(f"wrote {rel}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
