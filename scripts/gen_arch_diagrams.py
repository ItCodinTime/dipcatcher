def _mmd_id(package: str) -> str:
    return package.replace(".", "_").replace("-", "_")


def render_module_deps(modules: list[str], edges: Counter[tuple[str, str]]) -> str:
    known_pkgs = {package_of(m) for m in modules}
    qf = sorted(p for p in known_pkgs if p == "quant_fund" or p.startswith("quant_fund."))
    fx = sorted(p for p in known_pkgs if p == "fx1" or p.startswith("fx1."))
    ghost = sorted(
        {dst for (_, dst) in edges if dst not in known_pkgs}
        | {src for (src, _) in edges if src not in known_pkgs}
    )
    lines = [GENERATED_HEADER, "flowchart LR"]
    for group, title in (("quant_fund", "quant_fund (harness)"), ("fx1", "fx1 (model project)")):
        members = qf if group == "quant_fund" else fx
        # Prefix the cluster id. Mermaid shares a namespace with node ids, and
        # the root package nodes are already named ``quant_fund`` and ``fx1``.
        lines.append(f'  subgraph cluster_{group}["{title}"]')
        for pkg in members:
            lines.append(f'    {_mmd_id(pkg)}["{pkg}"]')
        lines.append("  end")
    for pkg in ghost:
        lines.append(f'  {_mmd_id(pkg)}["{pkg}"]:::ghost')
    for (src, dst), count in sorted(edges.items()):
        if src == dst:
            continue
        lines.append(f"  {_mmd_id(src)} -->|{count}| {_mmd_id(dst)}")
    lines += [
        "  classDef ghost stroke-dasharray: 5 5,color:#888",
        "  %% ghost nodes are lazily referenced packages absent from this tree",
    ]
    return "\n".join(lines) + "\n"


def render_data_flow() -> str:
    """ingest → features → model → backtest/paper → receipt. Labels come from anchors."""
    lines = [GENERATED_HEADER, "flowchart LR"]
    for group in DATA_FLOW_GROUPS:
        lines.append(f'  subgraph cluster_{group.group_id}["{group.title}"]')
        for node in group.nodes:
            lines.append(f'    {node.node_id}["{_node_label(node)}"]')
        lines.append("  end")
    for chain in DATA_FLOW_CHAINS:
        lines.append("  " + " --> ".join(chain))
    return "\n".join(lines) + "\n"


def render_paper_loop() -> str:
    """Sequence diagram of ``run_paper_loop``. Participant aliases come from anchors."""
    lines = [GENERATED_HEADER, "sequenceDiagram", "  autonumber"]
    for node in PAPER_LOOP_PARTICIPANTS:
        lines.append(f"  participant {node.node_id} as {_participant_alias(node)}")
    lines.extend(PAPER_LOOP_MESSAGES)
    return "\n".join(lines) + "\n"


def render_coverage(modules: list[str], edges: Counter[tuple[str, str]]) -> str:
    counts: Counter[str] = Counter(package_of(m) for m in modules)
    lines = ["| Package | Modules |", "|---|---|"]
    for pkg in sorted(counts):
        lines.append(f"| `{pkg}` | {counts[pkg]} |")
    n_edges = sum(1 for (s, d) in edges if s != d)
    lines.append("")
    lines.append(f"- Modules scanned: **{len(modules)}**")
    lines.append(f"- Packages: **{len(counts)}**")
    lines.append(f"- Cross-package import edges: **{n_edges}**")
    return "\n".join(lines) + "\n"


