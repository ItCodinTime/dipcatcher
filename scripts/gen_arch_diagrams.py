#!/usr/bin/env python3
"""Regenerate the architecture-atlas diagrams and freshness manifest.

Reads first-party imports out of ``src/`` with the stdlib ``ast`` parser (no
third-party dependency) and emits deterministic Mermaid artifacts:

- ``docs/architecture/module_deps.mmd`` — package-level import graph,
- ``docs/architecture/data_flow.mmd`` — ingest → features → model →
  backtest/paper → receipt,
- ``docs/architecture/paper_loop_sequence.mmd`` — paper/shadow event loop,
- ``docs/architecture/manifest.json`` — sorted module list + package edges,
- generated blocks spliced into ``docs/ARCHITECTURE_ATLAS.md`` between
  ``<!-- BEGIN GENERATED: <name> -->`` / ``<!-- END GENERATED: <name> -->``
  markers.

``--check`` regenerates everything in memory and exits 1 when any committed
artifact (``.mmd``, ``manifest.json``, or an embedded atlas block) is stale.
Determinism contract: every emitted collection is sorted, so byte-for-byte
comparison is stable across runs and platforms.

Curated diagrams (data flow, paper loop) are declared in this file but every
node carries a ``module::symbol`` anchor that is verified against the parsed
source — renaming or deleting an anchored symbol fails generation (and
``--check``), so the pictures cannot silently drift from the code they claim
to describe.
"""

